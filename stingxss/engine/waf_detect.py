"""
StingXSS — engine/waf_detect.py
WAF fingerprinting and evasion strategy selection.

Probes the target with a known-bad payload and analyses the response
(status code, headers, body) to identify the WAF in front of it.
Returns the WAF name and an ordered list of evasion strategies to try.
"""

