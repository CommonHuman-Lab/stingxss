# Generic block signals (no specific WAF identified)
_GENERIC_BLOCK_BODIES = [
  r"Access Denied",
  r"Forbidden",
  r"Request Blocked",
  r"Security violation",
  r"Illegal request",
  r"Attack detected",
]

# Probe payload — something that should trigger most WAFs
_PROBE_PAYLOAD = "<script>alert(1)</script>"


# ---------------------------------------------------------------------------
# Detection
# ---------------------------------------------------------------------------

@dataclass
class WafResult:
  detected:    bool
  name:        Optional[str]
  evasions:    List[str]
  confidence:  str  # "high" | "medium" | "low" | "none"


def detect(injector, url: str, param: Optional[str] = None) -> WafResult:
  """
  Fire a probe request and fingerprint the WAF from the response.

  injector: engine.injector.Injector instance
  url:      target URL (GET probe if param is None)
  param:    if provided, inject as a GET parameter value
  """
  try:
    if param:
      probe_url = _inject_param(url, param, _PROBE_PAYLOAD)
    else:
      sep = "&" if "?" in url else "?"
      probe_url = f"{url}{sep}q={_PROBE_PAYLOAD}"

    resp = injector.get(probe_url)
  except Exception:
    return WafResult(detected=False, name=None, evasions=[EVASION_NONE], confidence="none")

  # Baseline: if we get a 2xx with the payload reflected, no WAF
  if resp.status_code < 400 and _PROBE_PAYLOAD.lower() in resp.text.lower():
    return WafResult(detected=False, name=None, evasions=[EVASION_NONE], confidence="none")

  headers_lower: Dict[str, str] = {k.lower(): v.lower() for k, v in resp.headers.items()}
  body = resp.text

  best_match: Optional[WafSignature] = None
  best_score = 0

  for sig in _SIGNATURES:
    score = 0

    for hdr, pattern in sig.header_clues:
      val = headers_lower.get(hdr, "")
      if val and re.search(pattern, val, re.IGNORECASE):
        score += 2

    for pattern in sig.body_clues:
      if re.search(pattern, body, re.IGNORECASE):
        score += 1

    if resp.status_code in sig.status_codes:
      score += 1

    if score > best_score:
      best_score = score
      best_match = sig

  if best_match and best_score >= 2:
    confidence = "high" if best_score >= 4 else "medium"
    return WafResult(
      detected=True,
      name=best_match.name,
      evasions=best_match.evasions,
      confidence=confidence,
    )

  # Generic block detected
  if resp.status_code in (403, 406, 429, 503):
    return WafResult(
      detected=True,
      name="Generic WAF",
      evasions=[EVASION_CASE_MIXING, EVASION_HTML_ENCODE, EVASION_UNICODE, EVASION_COMMENT_BREAK],
      confidence="low",
    )

  for pattern in _GENERIC_BLOCK_BODIES:
    if re.search(pattern, body, re.IGNORECASE):
      return WafResult(
        detected=True,
        name="Generic WAF",
        evasions=[EVASION_CASE_MIXING, EVASION_HTML_ENCODE, EVASION_UNICODE],
        confidence="low",
      )

  return WafResult(detected=False, name=None, evasions=[EVASION_NONE], confidence="none")


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _inject_param(url: str, param: str, value: str) -> str:
  """Replace the value of `param` in the URL query string with `value`."""
  parsed  = up.urlparse(url)
  qs      = up.parse_qs(parsed.query, keep_blank_values=True)
  qs[param] = [value]
  new_qs  = up.urlencode(qs, doseq=True)
  return up.urlunparse(parsed._replace(query=new_qs))
